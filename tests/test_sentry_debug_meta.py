"""Run with JDK and Kotlin CLI: python3 -m unittest discover -s tests -p test_sentry_debug_meta.py -v.

Executes the actual Gradle doLast file transformation without configuring Android
or other platform targets. This does not verify whole-APK reproducibility.
"""
from pathlib import Path
import subprocess
import tempfile
import unittest


class SentryDebugMetaTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory()
        cls.addClassCleanup(cls.temp.cleanup)
        cls.root = Path(cls.temp.name)
        build = (Path(__file__).resolve().parents[1] / 'composeApp/build.gradle.kts').read_text()
        start = build.index('val content = metaPropFile.readLines()')
        end = build.index('metaPropFile.writeText(content)', start) + len('metaPropFile.writeText(content)')
        source = cls.root / 'SentryMeta.kt'
        source.write_text('fun main(args: Array<String>) {\n'
                          'val metaPropFile = java.io.File(args.single())\n'
                          + build[start:end] + '\n}\n')
        subprocess.run(['kotlinc', str(source), '-d', str(cls.root / 'classes')], check=True)

    def normalize(self, content):
        target = self.root / 'sentry-debug-meta.properties'
        target.write_bytes(content)
        subprocess.run(['kotlin', '-classpath', str(self.root / 'classes'),
                        'SentryMetaKt', str(target)], check=True)
        return target.read_bytes()

    uuid = b'io.sentry.ProguardUuids=8295125e-4b07-3fd4-a9fc-533694577253'
    tool = b'io.sentry.build-tool=gradle'

    def test_reversed_input_has_identical_bytes(self):
        expected = self.uuid + b'\n' + self.tool
        self.assertEqual(expected, self.normalize(self.tool + b'\n' + self.uuid))
        self.assertEqual(expected, self.normalize(expected))

    def test_timestamp_comments_are_removed(self):
        self.assertEqual(self.uuid + b'\n' + self.tool, self.normalize(
            b'#Generated by Sentry\n#Tue Oct 27 12:00:00 UTC 2026\n'
            + self.tool + b'\n' + self.uuid + b'\n'))

    def test_values_and_escaped_text_are_preserved(self):
        extra = b'io.sentry.extra=space value\\:equals=hash#\\u4e2d'
        self.assertEqual(self.uuid + b'\n' + self.tool + b'\n' + extra,
                         self.normalize(extra + b'\n' + self.tool + b'\n' + self.uuid))

    def test_line_endings_and_repeated_processing_are_deterministic(self):
        result = self.normalize(self.tool + b'\r\n' + self.uuid + b'\r\n')
        self.assertEqual(self.uuid + b'\n' + self.tool, result)
        self.assertEqual(result, self.normalize(result))


if __name__ == '__main__':
    unittest.main()
